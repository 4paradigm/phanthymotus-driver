def test_g1_pinned_files_match_exact_local_git_objects():
    lock = json.loads((DRIVER / "deploy/G1_REFERENCE.json").read_text())
    commit = lock["reference_commit"]
    tree = subprocess.check_output(
        ["git", "rev-parse", f"{commit}:unitree/g1"], cwd=ROOT, text=True).strip()
    assert tree == lock["g1_tree"]
    for name, digest in lock["files"].items():
        data = subprocess.check_output(["git", "show", f"{commit}:unitree/g1/{name}"], cwd=ROOT)
        assert hashlib.sha256(data).hexdigest() == digest
    # The lock is a historical development reference. Updating main may change
    # G1 independently; never require reverting those upstream files to the pin.


def test_staged_docker_context_has_all_copy_inputs_and_install_fragment(tmp_path):
    context = tmp_path / "context"
    shutil.copytree(DRIVER, context)
    shutil.copytree(ROOT / "common", context / "common")
    dockerfile = (context / "Dockerfile").read_text()
    variables = dict(re.findall(r"^ARG (\w+)=(.+)$", dockerfile, re.M))
    instructions = dockerfile.replace("\\\n", " ").splitlines()
    destinations = {}
    for instruction in instructions:
        if not instruction.startswith("COPY "):
            continue
        tokens = shlex.split(instruction)[1:]
        if tokens[0].startswith("--from="):
            continue  # Input is generated by the interfaces build stage.
        sources, destination = tokens[:-1], tokens[-1]
        for source in sources:
            source = re.sub(r"\$\{(\w+)\}", lambda match: variables[match[1]], source)
            assert (context / source).exists(), f"Missing COPY input: {source}"
        destinations[destination] = sources
    assert destinations["/deploy/"] == ["deploy/"]
    assert destinations["/work/common/"] == ["common/"]
    contract.validate_fragment(contract.load(context / "deploy/service.yml"))
    overlay = contract.load(context / "deploy/service.supervised.yml")
    assert set(overlay) == {contract.DRIVER_SERVICE}


def test_s10_authored_code_and_documentation_use_english():
    for path in DRIVER.rglob("*"):
        if "vendor" in path.relative_to(DRIVER).parts or not path.is_file():
            continue
        if path.suffix in {".py", ".md", ".yaml", ".yml"} or path.name == "Dockerfile":
            assert not re.search(r"[\u3400-\u9fff]", path.read_text()), str(path)
