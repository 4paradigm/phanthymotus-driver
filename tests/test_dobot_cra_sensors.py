def packet(mode=4, brake=0, angle=90, robot_type=113):
    # Independent offsets from TCP/IP V4.6.6, not a packet generated by SDK dtype.
    data = bytearray(1440)
    struct.pack_into("<H", data, 0, 1440)
    struct.pack_into("<Q", data, 24, mode)
    struct.pack_into("<Q", data, 32, 123456)
    struct.pack_into("<Q", data, 48, 0x0123456789ABCDEF)
    struct.pack_into("<6d", data, 432, angle, -30, 0, 0, 0, 0)
    struct.pack_into("<6d", data, 480, 180, 0, 0, 0, 0, 0)
    struct.pack_into("<6d", data, 624, 100, 200, 300, 10, 20, 30)
    data[1025] = brake
    data[1031] = robot_type
    return bytes(data)


def wait_until(predicate, timeout=2):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if predicate():
            return
        time.sleep(0.005)
    raise AssertionError("condition not reached")


class FakeConnection:
    def __init__(self, chunks):
        self.chunks = list(chunks)
        self.closed = threading.Event()
        self.receive_gate = threading.Event()

    def set_timeout(self, *args):
        pass

    def connect(self):
        pass

    def receive_bytes(self, count):
        if self.chunks:
            chunk = self.chunks.pop(0)
            if isinstance(chunk, Exception):
                raise chunk
            return chunk
        self.receive_gate.set()
        self.closed.wait(2)
        raise ConnectionError("closed")

    def disconnect(self):
        self.closed.set()


def running_client(chunks, **config):
    connection = FakeConnection(chunks)
    calls = []

    def factory(address, port):
        calls.append((address, port))
        return connection

    client = FeedbackClient(
        {"controller_ip": "127.0.0.1", **config}, connection_factory=factory,
    )
    client.start()
    return client, connection, calls


