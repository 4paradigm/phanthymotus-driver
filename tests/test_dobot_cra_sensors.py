@pytest.mark.parametrize("change", ["length", "magic", "truncated", "nan"])
def test_bad_packets_are_rejected(change):
    data = bytearray(packet())
    if change == "length":
        data[0] = 0
    elif change == "magic":
        data[48] = 0
    elif change == "truncated":
        del data[-1]
    else:
        struct.pack_into("<d", data, 432, float("nan"))
    with pytest.raises(ValueError):
        decode_packet(bytes(data))


def test_fragmented_coalesced_and_misaligned_stream():
    first, second = packet(angle=1), packet(angle=2)
    stream = PacketStream()
    assert stream.feed(b"garbage" + first[:1]) == []
    assert stream.feed(first[1:900]) == []
    assert stream.feed(first[900:] + second + second[:500]) == [first, second]
    assert stream.feed(second[500:]) == [second]
    assert stream.discarded_bytes == 7
    assert not stream.buffer


def test_stream_recovers_from_bad_magic_and_bounds_garbage():
    stream = PacketStream()
